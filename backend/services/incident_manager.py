"""
FedSentinel incident management.

IncidentManager converts security decisions produced by the
SecurityPipeline into operational security incidents.

Responsibilities:
    - create incidents from a completed security round
    - identify affected clients
    - collect security evidence
    - determine incident severity
    - track incident lifecycle
    - resolve incidents

Important:
    IncidentManager does not perform detection.
    It consumes evidence and decisions generated by the existing
    security pipeline.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from datetime import datetime, timezone
from typing import Any

from backend.core.types import (
    Action,
    ThreatHypothesis,
    ThreatLevel,
    TrustStatus,
)
from backend.services.security_pipeline import (
    ClientSecurityResult,
    SecurityRoundResult,
)


@dataclass
class ManagedIncident:
    """
    Runtime representation of one FedSentinel security incident.
    """

    incident_id: str
    round_id: str

    title: str
    description: str

    severity: ThreatLevel
    status: str

    affected_clients: list[str] = field(default_factory=list)
    evidence: list[str] = field(default_factory=list)

    primary_client_id: str | None = None
    hypothesis: ThreatHypothesis = ThreatHypothesis.NONE
    recommended_action: Action = Action.MONITOR

    risk_score: float = 0.0
    confidence: float = 0.0

    created_at: datetime = field(
        default_factory=lambda: datetime.now(timezone.utc)
    )
    updated_at: datetime = field(
        default_factory=lambda: datetime.now(timezone.utc)
    )
    resolved_at: datetime | None = None

    resolution: str | None = None


class IncidentManager:
    """
    Manage operational security incidents.

    Detection remains completely independent.

    The IncidentManager only interprets the already-generated
    security evidence and trust decisions.
    """

    def __init__(self) -> None:
        self._incidents: dict[str, ManagedIncident] = {}

    # ---------------------------------------------------------
    # Severity
    # ---------------------------------------------------------

    @staticmethod
    def _determine_severity(
        result: ClientSecurityResult,
    ) -> ThreatLevel:
        """
        Determine incident severity from an existing trust decision.

        This does not create a new detection score.
        """

        if result.trust is None:
            return ThreatLevel.INFO

        trust = result.trust

        if trust.status == TrustStatus.QUARANTINED:
            if trust.hypothesis in (
                ThreatHypothesis.MODEL_POISONING,
                ThreatHypothesis.BACKDOOR,
                ThreatHypothesis.DATA_POISONING,
                ThreatHypothesis.LABEL_POISONING,
            ):
                return ThreatLevel.CRITICAL

            return ThreatLevel.HIGH

        if trust.status == TrustStatus.SUSPICIOUS:
            return ThreatLevel.HIGH

        if trust.status == TrustStatus.REVIEW:
            return ThreatLevel.MEDIUM

        return ThreatLevel.LOW

    # ---------------------------------------------------------
    # Evidence collection
    # ---------------------------------------------------------

    @staticmethod
    def _collect_evidence(
        result: ClientSecurityResult,
    ) -> list[str]:
        """
        Collect the evidence already generated for a client.
        """

        evidence = list(result.evidence_items)

        if result.layer2 is not None:
            evidence.append(
                "L2 peer and anomaly analysis available."
            )

        if result.layer3 is not None:
            evidence.append(
                f"L3 influence evidence: "
                f"{result.layer3.influence_score:+.2f}."
            )

        if result.layer4 is not None:
            evidence.append(
                "L4 counterfactual evidence available."
            )

        if result.layer5 is not None:
            evidence.append(
                f"L5 attribution evidence: "
                f"{result.layer5.evidence_score:.2f}."
            )

        if result.trust is not None:
            evidence.append(
                f"Trust decision: "
                f"{result.trust.status.value}."
            )

        return evidence

    # ---------------------------------------------------------
    # Incident creation
    # ---------------------------------------------------------

    def create_incident(
        self,
        *,
        incident_id: str,
        round_id: str,
        client_result: ClientSecurityResult,
    ) -> ManagedIncident:
        """
        Create an incident for a security-relevant client result.
        """

        if not incident_id:
            raise ValueError(
                "incident_id cannot be empty."
            )

        if not round_id:
            raise ValueError(
                "round_id cannot be empty."
            )

        if incident_id in self._incidents:
            raise ValueError(
                f"Incident '{incident_id}' already exists."
            )

        now = datetime.now(timezone.utc)

        trust = client_result.trust

        if trust is not None:
            hypothesis = trust.hypothesis
            action = trust.action
        else:
            hypothesis = ThreatHypothesis.NONE
            action = Action.MONITOR

        severity = self._determine_severity(
            client_result
        )

        evidence = self._collect_evidence(
            client_result
        )

        if hypothesis == ThreatHypothesis.NONE:
            title = (
                f"Security review for "
                f"{client_result.client_id}"
            )
        else:
            title = (
                f"{hypothesis.value.replace('_', ' ')} "
                f"detected for "
                f"{client_result.client_id}"
            )

        description = (
            f"FedSentinel identified security-relevant "
            f"behavior from client "
            f"{client_result.client_id} during round "
            f"{round_id}. "
            f"The incident is based on accumulated "
            f"security evidence and trust analysis."
        )

        incident = ManagedIncident(
            incident_id=incident_id,
            round_id=round_id,
            title=title,
            description=description,
            severity=severity,
            status="OPEN",
            affected_clients=[
                client_result.client_id
            ],
            evidence=evidence,
            primary_client_id=client_result.client_id,
            hypothesis=hypothesis,
            recommended_action=action,
            risk_score=(trust.risk_score if trust is not None else 0.0),
            confidence=(getattr(trust, "confidence", 0.0) if trust is not None else 0.0),
            created_at=now,
            updated_at=now,
        )

        self._incidents[incident_id] = incident

        return incident

    # ---------------------------------------------------------
    # Create incidents from a round
    # ---------------------------------------------------------

    def create_from_round(
        self,
        *,
        round_result: SecurityRoundResult,
    ) -> list[ManagedIncident]:
        """
        Create incidents for all clients requiring operational
        attention.

        A client becomes incident-worthy when:

            - quarantined
            - Trust status is SUSPICIOUS
            - Trust status is QUARANTINED
            - recommended action is QUARANTINE
            - recommended action is BLOCK
        """

        incidents: list[ManagedIncident] = []

        for client_id, result in (
            round_result.client_results.items()
        ):
            should_create = result.quarantined

            if result.trust is not None:
                should_create = should_create or (
                    result.trust.status
                    in (
                        TrustStatus.SUSPICIOUS,
                        TrustStatus.QUARANTINED,
                    )
                )

                should_create = should_create or (
                    result.trust.action
                    in (
                        Action.QUARANTINE,
                        Action.BLOCK,
                    )
                )

            if not should_create:
                continue

            incident_id = (
                f"INC-{round_result.round_id}-{client_id}"
            )

            if incident_id in self._incidents:
                incidents.append(
                    self._incidents[incident_id]
                )
                continue

            incident = self.create_incident(
                incident_id=incident_id,
                round_id=round_result.round_id,
                client_result=result,
            )

            incidents.append(incident)

        return incidents

    # ---------------------------------------------------------
    # Lookup
    # ---------------------------------------------------------

    def get_incident(
        self,
        incident_id: str,
    ) -> ManagedIncident:
        """
        Return an incident by ID.
        """

        try:
            return self._incidents[incident_id]
        except KeyError:
            raise KeyError(
                f"Incident '{incident_id}' does not exist."
            ) from None

    def list_incidents(self) -> list[ManagedIncident]:
        """
        Return incidents ordered by creation time.
        """

        return sorted(
            self._incidents.values(),
            key=lambda item: item.created_at,
        )

    # ---------------------------------------------------------
    # Incident lifecycle
    # ---------------------------------------------------------

    def resolve_incident(
        self,
        *,
        incident_id: str,
        resolution: str,
    ) -> ManagedIncident:
        """
        Resolve an open incident.
        """

        if not resolution.strip():
            raise ValueError(
                "resolution cannot be empty."
            )

        incident = self.get_incident(
            incident_id
        )

        if incident.status == "RESOLVED":
            raise RuntimeError(
                f"Incident '{incident_id}' is already resolved."
            )

        now = datetime.now(timezone.utc)

        incident.status = "RESOLVED"
        incident.resolution = resolution
        incident.resolved_at = now
        incident.updated_at = now

        return incident

    def reopen_incident(
        self,
        *,
        incident_id: str,
    ) -> ManagedIncident:
        """
        Reopen a resolved incident.
        """

        incident = self.get_incident(
            incident_id
        )

        if incident.status != "RESOLVED":
            raise RuntimeError(
                f"Incident '{incident_id}' is not resolved."
            )

        now = datetime.now(timezone.utc)

        incident.status = "OPEN"
        incident.resolution = None
        incident.resolved_at = None
        incident.updated_at = now

        return incident

    # ---------------------------------------------------------
    # Utility
    # ---------------------------------------------------------

    def clear(self) -> None:
        """
        Clear in-memory incidents.

        Primarily useful for tests and local development.
        """

        self._incidents.clear()


