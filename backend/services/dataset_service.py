# ============================================================================
# STORAGE CONFIGURATION
# ============================================================================

DATASET_STORAGE_ROOT = (
    Path(__file__).resolve().parents[2]
    / "data"
    / "hospital_datasets"
)

MAX_DATASET_SIZE = 100 * 1024 * 1024  # 100 MB
CHUNK_SIZE = 1024 * 1024


# ============================================================================
# HELPERS
# ============================================================================

def _safe_component(value: str) -> str:
    """
    Allow only safe filesystem path components.
    """

    value = value.strip()

    if not value:
        raise ValueError("Empty path component.")

    allowed = (
        "abcdefghijklmnopqrstuvwxyz"
        "ABCDEFGHIJKLMNOPQRSTUVWXYZ"
        "0123456789"
        "._-"
    )

    if any(character not in allowed for character in value):
        raise ValueError(
            f"Unsafe path component: {value}"
        )

    return value


def _version_storage_dir(
    hospital_id: str,
    dataset_id: str,
    version: str,
) -> Path:
    """
    Build deterministic local storage path.

    IDs are generated by the application and version names are
    validated before reaching this function.
    """

    hospital = _safe_component(hospital_id)
    dataset = _safe_component(dataset_id)
    version = _safe_component(version)

    return (
        DATASET_STORAGE_ROOT
        / hospital
        / dataset
        / version
    )


def _validate_npz_dataset(
    path: Path,
    *,
    expected_num_classes: int,
) -> tuple[int, int]:
    """
    Validate a MNIST-compatible NPZ dataset.

    Supported array naming conventions:

        x_train / y_train
        x / y
        images / labels

    Pickled Python objects are explicitly disabled.
    """

    try:
        with np.load(
            path,
            allow_pickle=False,
        ) as data:

            available = set(data.files)

            pairs = [
                ("x_train", "y_train"),
                ("x", "y"),
                ("images", "labels"),
            ]

            x_key = None
            y_key = None

            for candidate_x, candidate_y in pairs:
                if (
                    candidate_x in available
                    and candidate_y in available
                ):
                    x_key = candidate_x
                    y_key = candidate_y
                    break

            if x_key is None or y_key is None:
                raise ValueError(
                    "NPZ must contain one of: "
                    "x_train/y_train, x/y, or images/labels."
                )

            x = np.asarray(data[x_key])
            y = np.asarray(data[y_key])

            if x.ndim < 2:
                raise ValueError(
                    "Input samples must have at least 2 dimensions."
                )

            if y.ndim != 1:
                y = y.reshape(-1)

            sample_count = int(x.shape[0])

            if sample_count <= 0:
                raise ValueError(
                    "Dataset contains no samples."
                )

            if len(y) != sample_count:
                raise ValueError(
                    "Number of labels does not match "
                    "number of samples."
                )

            if not np.issubdtype(
                y.dtype,
                np.integer,
            ):
                if not np.all(
                    np.isfinite(y)
                ):
                    raise ValueError(
                        "Labels contain non-finite values."
                    )

                if not np.all(
                    np.equal(y, np.floor(y))
                ):
                    raise ValueError(
                        "Labels must contain integer class IDs."
                    )

            y = y.astype(
                np.int64,
                copy=False,
            )

            if not np.all(
                np.isfinite(x)
            ):
                raise ValueError(
                    "Input samples contain non-finite values."
                )

            min_label = int(y.min())
            max_label = int(y.max())

            if min_label < 0:
                raise ValueError(
                    "Labels cannot be negative."
                )

            if max_label >= expected_num_classes:
                raise ValueError(
                    f"Label {max_label} exceeds the configured "
                    f"class range 0-{expected_num_classes - 1}."
                )

            class_count = int(
                np.unique(y).size
            )

            if class_count < 2:
                raise ValueError(
                    "Dataset must contain at least two classes."
                )

            return sample_count, class_count

    except ValueError:
        raise

    except Exception as exc:
        raise ValueError(
            f"Unable to read NPZ dataset safely: {exc}"
        ) from exc


def _save_upload_and_hash(
    upload: UploadFile,
    destination: Path,
) -> tuple[int, str]:
    """
    Stream upload to disk while calculating SHA-256.

    The file is never loaded entirely into memory.
    """

    destination.parent.mkdir(
        parents=True,
        exist_ok=True,
    )

    hasher = hashlib.sha256()
    total_size = 0

    try:
        with destination.open(
            "wb"
        ) as output:

            while True:
                chunk = upload.file.read(
                    CHUNK_SIZE
                )

                if not chunk:
                    break

                total_size += len(chunk)

                if total_size > MAX_DATASET_SIZE:
                    raise HTTPException(
                        status_code=status.HTTP_413_REQUEST_ENTITY_TOO_LARGE,
                        detail=(
                            "Dataset exceeds the maximum "
                            "allowed size of 100 MB."
                        ),
                    )

                hasher.update(chunk)
                output.write(chunk)

    except HTTPException:
        destination.unlink(
            missing_ok=True
        )
        raise

    except Exception:
        destination.unlink(
            missing_ok=True
        )
        raise

    return total_size, hasher.hexdigest()


class DatasetService:

    # ========================================================================
    # LIST
    # ========================================================================

    @staticmethod
    def list_datasets(
        db: Session,
        *,
        hospital_id: str,
    ) -> list[Dataset]:

        return (
            db.query(Dataset)
            .filter(
                Dataset.hospital_id == hospital_id
            )
            .order_by(Dataset.created_at.desc())
            .all()
        )

    # ========================================================================
    # GET
    # ========================================================================

    @staticmethod
    def get_dataset(
        db: Session,
        *,
        hospital_id: str,
        dataset_id: str,
    ) -> Dataset:

        dataset = (
            db.query(Dataset)
            .filter(
                Dataset.id == dataset_id,
                Dataset.hospital_id == hospital_id,
            )
            .first()
        )

        if dataset is None:
            raise HTTPException(
                status_code=status.HTTP_404_NOT_FOUND,
                detail="Dataset not found.",
            )

        return dataset

    # ========================================================================
    # CREATE
    # ========================================================================

    @staticmethod
    def create_dataset(
        db: Session,
        *,
        hospital_id: str,
        actor_user_id: str,
        payload: DatasetCreate,
    ) -> Dataset:

        hospital = (
            db.query(Hospital)
            .filter(
                Hospital.id == hospital_id
            )
            .first()
        )

        if hospital is None:
            raise HTTPException(
                status_code=status.HTTP_404_NOT_FOUND,
                detail="Hospital not found.",
            )

        if not hospital.is_eligible:
            raise HTTPException(
                status_code=status.HTTP_409_CONFLICT,
                detail=(
                    "Hospital is not currently eligible "
                    "to manage federation datasets."
                ),
            )

        dataset = Dataset(
            hospital_id=hospital_id,
            name=payload.name.strip(),
            dataset_type=payload.dataset_type.strip().upper(),
            sample_count=payload.sample_count,
            num_classes=payload.num_classes,
            is_active=True,
        )

        db.add(dataset)
        db.commit()
        db.refresh(dataset)

        record_audit(
            db,
            actor_user_id=actor_user_id,
            action="DATASET_CREATED",
            resource_type="dataset",
            resource_id=dataset.id,
            result="SUCCESS",
            metadata={
                "hospital_id": hospital_id,
                "dataset_name": dataset.name,
                "dataset_type": dataset.dataset_type,
                "sample_count": dataset.sample_count,
                "num_classes": dataset.num_classes,
            },
        )

        return dataset

    # ========================================================================
    # UPDATE
    # ========================================================================

    @staticmethod
    def update_dataset(
        db: Session,
        *,
        hospital_id: str,
        actor_user_id: str,
        dataset_id: str,
        payload: DatasetUpdate,
    ) -> Dataset:

        dataset = DatasetService.get_dataset(
            db,
            hospital_id=hospital_id,
            dataset_id=dataset_id,
        )

        if not dataset.is_active:
            raise HTTPException(
                status_code=status.HTTP_409_CONFLICT,
                detail="Inactive dataset cannot be edited.",
            )

        if payload.name is not None:
            dataset.name = payload.name.strip()

        if payload.dataset_type is not None:
            dataset.dataset_type = (
                payload.dataset_type.strip().upper()
            )

        if payload.num_classes is not None:
            dataset.num_classes = payload.num_classes

        db.commit()
        db.refresh(dataset)

        record_audit(
            db,
            actor_user_id=actor_user_id,
            action="DATASET_UPDATED",
            resource_type="dataset",
            resource_id=dataset.id,
            result="SUCCESS",
        )

        return dataset

    # ========================================================================
    # CREATE VERSION - METADATA
    # ========================================================================

    @staticmethod
    def create_version(
        db: Session,
        *,
        hospital_id: str,
        actor_user_id: str,
        dataset_id: str,
        payload: DatasetVersionCreate,
    ) -> DatasetVersion:

        dataset = DatasetService.get_dataset(
            db,
            hospital_id=hospital_id,
            dataset_id=dataset_id,
        )

        if not dataset.is_active:
            raise HTTPException(
                status_code=status.HTTP_409_CONFLICT,
                detail="Cannot add a version to an inactive dataset.",
            )

        existing_version = (
            db.query(DatasetVersion)
            .filter(
                DatasetVersion.dataset_id == dataset.id,
                DatasetVersion.version == payload.version,
            )
            .first()
        )

        if existing_version is not None:
            raise HTTPException(
                status_code=status.HTTP_409_CONFLICT,
                detail="Dataset version already exists.",
            )

        version = DatasetVersion(
            dataset_id=dataset.id,
            version=payload.version,
            sample_count=payload.sample_count,
            fingerprint=payload.fingerprint,
        )

        db.add(version)

        dataset.sample_count = payload.sample_count

        db.commit()
        db.refresh(version)

        record_audit(
            db,
            actor_user_id=actor_user_id,
            action="DATASET_VERSION_CREATED",
            resource_type="dataset",
            resource_id=dataset.id,
            result="SUCCESS",
            metadata={
                "version_id": version.id,
                "version": version.version,
                "sample_count": version.sample_count,
                "fingerprint": version.fingerprint,
                "source": "metadata",
            },
        )

        return version

    # ========================================================================
    # REAL DATASET UPLOAD
    # ========================================================================

    @staticmethod
    def upload_version(
        db: Session,
        *,
        hospital_id: str,
        actor_user_id: str,
        dataset_id: str,
        version_name: str,
        upload: UploadFile,
    ) -> tuple[DatasetVersion, int, str]:

        dataset = DatasetService.get_dataset(
            db,
            hospital_id=hospital_id,
            dataset_id=dataset_id,
        )

        if not dataset.is_active:
            raise HTTPException(
                status_code=status.HTTP_409_CONFLICT,
                detail=(
                    "Cannot upload a version to an inactive dataset."
                ),
            )

        version_name = version_name.strip()

        if not version_name:
            raise HTTPException(
                status_code=status.HTTP_422_UNPROCESSABLE_ENTITY,
                detail="Version name cannot be empty.",
            )

        try:
            _safe_component(version_name)
        except ValueError:
            raise HTTPException(
                status_code=status.HTTP_422_UNPROCESSABLE_ENTITY,
                detail=(
                    "Version name contains unsafe characters. "
                    "Use letters, numbers, '.', '_' or '-'."
                ),
            )

        existing_version = (
            db.query(DatasetVersion)
            .filter(
                DatasetVersion.dataset_id == dataset.id,
                DatasetVersion.version == version_name,
            )
            .first()
        )

        if existing_version is not None:
            raise HTTPException(
                status_code=status.HTTP_409_CONFLICT,
                detail="Dataset version already exists.",
            )

        filename = upload.filename or "dataset.npz"

        if not filename.lower().endswith(".npz"):
            raise HTTPException(
                status_code=status.HTTP_415_UNSUPPORTED_MEDIA_TYPE,
                detail=(
                    "Only MNIST-compatible .npz datasets "
                    "are currently supported."
                ),
            )

        storage_dir = _version_storage_dir(
            hospital_id,
            dataset.id,
            version_name,
        )

        storage_dir.mkdir(
            parents=True,
            exist_ok=True,
        )

        final_path = storage_dir / "dataset.npz"

        if final_path.exists():
            raise HTTPException(
                status_code=status.HTTP_409_CONFLICT,
                detail="Dataset artifact already exists.",
            )

        temp_fd, temp_name = tempfile.mkstemp(
            prefix="upload_",
            suffix=".npz",
            dir=str(storage_dir),
        )

        os.close(temp_fd)

        temp_path = Path(temp_name)

        try:
            file_size, fingerprint = (
                _save_upload_and_hash(
                    upload,
                    temp_path,
                )
            )

            if file_size == 0:
                raise HTTPException(
                    status_code=status.HTTP_422_UNPROCESSABLE_ENTITY,
                    detail="Uploaded dataset is empty.",
                )

            try:
                sample_count, class_count = (
                    _validate_npz_dataset(
                        temp_path,
                        expected_num_classes=dataset.num_classes,
                    )
                )
            except ValueError as exc:
                raise HTTPException(
                    status_code=status.HTTP_422_UNPROCESSABLE_ENTITY,
                    detail=f"Dataset validation failed: {exc}",
                ) from exc

            temp_path.replace(final_path)

            version = DatasetVersion(
                dataset_id=dataset.id,
                version=version_name,
                sample_count=sample_count,
                fingerprint=fingerprint,
            )

            db.add(version)

            dataset.sample_count = sample_count

            db.commit()
            db.refresh(version)

            record_audit(
                db,
                actor_user_id=actor_user_id,
                action="DATASET_VERSION_UPLOADED",
                resource_type="dataset",
                resource_id=dataset.id,
                result="SUCCESS",
                metadata={
                    "version_id": version.id,
                    "version": version.version,
                    "filename": filename,
                    "file_size": file_size,
                    "fingerprint": fingerprint,
                    "sample_count": sample_count,
                    "class_count": class_count,
                    "storage": "hospital_local",
                    "validation": "NPZ_SAFE_NO_PICKLE",
                },
            )

            return version, file_size, fingerprint, class_count

        except HTTPException:
            temp_path.unlink(
                missing_ok=True
            )
            raise

        except Exception:
            temp_path.unlink(
                missing_ok=True
            )

            # Avoid leaving a partial artifact.
            final_path.unlink(
                missing_ok=True
            )

            db.rollback()
            raise

        finally:
            upload.file.close()

    # ========================================================================
    # IMPORT DATASET VERSION FROM RECORD LINK / URL / LOCAL PATH
    # ========================================================================

    @staticmethod
    def import_version_from_link(
        db: Session,
        *,
        hospital_id: str,
        actor_user_id: str,
        dataset_id: str,
        version_name: str,
        record_link: str,
        format_type: str = "AUTO",
    ) -> tuple[DatasetVersion, int, str, int]:
        """
        Import a hospital-local dataset version from an external record URL,
        local path, or synthetic record source.

        The retrieved artifact is stored under the hospital enclave storage
        boundary and strictly validated.
        """
        dataset = DatasetService.get_dataset(
            db,
            hospital_id=hospital_id,
            dataset_id=dataset_id,
        )

        if not dataset.is_active:
            raise HTTPException(
                status_code=status.HTTP_409_CONFLICT,
                detail="Cannot add a version to an inactive dataset.",
            )

        version_name = version_name.strip()
        if not version_name:
            raise HTTPException(
                status_code=status.HTTP_422_UNPROCESSABLE_ENTITY,
                detail="Version name cannot be empty.",
            )

        try:
            _safe_component(version_name)
        except ValueError:
            raise HTTPException(
                status_code=status.HTTP_422_UNPROCESSABLE_ENTITY,
                detail=(
                    "Version name contains unsafe characters. "
                    "Use letters, numbers, '.', '_' or '-'."
                ),
            )

        existing_version = (
            db.query(DatasetVersion)
            .filter(
                DatasetVersion.dataset_id == dataset.id,
                DatasetVersion.version == version_name,
            )
            .first()
        )

        if existing_version is not None:
            raise HTTPException(
                status_code=status.HTTP_409_CONFLICT,
                detail=f"Dataset version '{version_name}' already exists.",
            )

        storage_dir = _version_storage_dir(
            hospital_id,
            dataset.id,
            version_name,
        )
        storage_dir.mkdir(parents=True, exist_ok=True)

        final_path = storage_dir / "dataset.npz"
        if final_path.exists():
            raise HTTPException(
                status_code=status.HTTP_409_CONFLICT,
                detail="Dataset artifact already exists.",
            )

        temp_name = f"link_import_{uuid.uuid4().hex[:8]}.npz"
        temp_path = storage_dir / temp_name

        try:
            record_link = record_link.strip()

            if record_link.startswith(("http://", "https://")):
                # Stream download from external medical record server / URL
                req = urllib.request.Request(
                    record_link,
                    headers={"User-Agent": "FedSentinel-Clinical/2.0"},
                )
                hasher = hashlib.sha256()
                total_bytes = 0

                with urllib.request.urlopen(req, timeout=20) as resp, open(temp_path, "wb") as f_out:
                    while True:
                        chunk = resp.read(CHUNK_SIZE)
                        if not chunk:
                            break
                        total_bytes += len(chunk)
                        if total_bytes > MAX_DATASET_SIZE:
                            raise HTTPException(
                                status_code=status.HTTP_413_REQUEST_ENTITY_TOO_LARGE,
                                detail="Remote dataset exceeds maximum permitted size (100MB).",
                            )
                        hasher.update(chunk)
                        f_out.write(chunk)

                if total_bytes == 0:
                    raise HTTPException(
                        status_code=status.HTTP_422_UNPROCESSABLE_ENTITY,
                        detail="Downloaded dataset artifact is empty.",
                    )

            else:
                # Local filesystem path (or file:// URI)
                clean_path = record_link
                if clean_path.startswith("file://"):
                    clean_path = clean_path[7:]
                
                src = Path(clean_path)
                if not src.is_absolute():
                    # check relative to workspace
                    src = Path(os.getcwd()) / clean_path

                # Special test / demo record generator if the path doesn't exist but has demo pattern
                if not src.exists() and ("demo" in record_link.lower() or "synthetic" in record_link.lower() or "sample" in record_link.lower()):
                    # Generate deterministic synthetic local clinical image dataset
                    rng = np.random.RandomState(42)
                    sample_count = 200
                    images = rng.randn(sample_count, 1, 28, 28).astype(np.float32)
                    labels = rng.randint(0, dataset.num_classes, size=(sample_count,)).astype(np.int64)
                    np.savez_compressed(temp_path, images=images, labels=labels)
                elif not src.exists():
                    raise HTTPException(
                        status_code=status.HTTP_404_NOT_FOUND,
                        detail=f"Record path not found on hospital local storage: {record_link}",
                    )
                else:
                    # Check format
                    if src.suffix.lower() == ".npz":
                        shutil.copyfile(src, temp_path)
                    elif src.suffix.lower() == ".csv":
                        # Parse CSV records (label in first column, 784 pixels in remaining columns)
                        try:
                            raw = np.loadtxt(src, delimiter=",")
                            if raw.ndim == 1:
                                raw = raw.reshape(1, -1)
                            labels = raw[:, 0].astype(np.int64)
                            pixels = raw[:, 1:].astype(np.float32)
                            if pixels.shape[1] == 784:
                                images = pixels.reshape(-1, 1, 28, 28)
                            else:
                                images = np.pad(pixels, ((0, 0), (0, max(0, 784 - pixels.shape[1]))))[:, :784].reshape(-1, 1, 28, 28)
                            if images.max() > 1.0:
                                images = images / 255.0
                            np.savez_compressed(temp_path, images=images, labels=labels)
                        except Exception as csv_exc:
                            raise HTTPException(
                                status_code=status.HTTP_422_UNPROCESSABLE_ENTITY,
                                detail=f"Failed to parse CSV record artifact: {csv_exc}",
                            ) from csv_exc
                    else:
                        raise HTTPException(
                            status_code=status.HTTP_415_UNSUPPORTED_MEDIA_TYPE,
                            detail="Supported record formats are .npz, .csv, or verified record URLs.",
                        )

            # Compute hash and file size of the local NPZ
            hasher = hashlib.sha256()
            file_size = 0
            with open(temp_path, "rb") as f:
                while True:
                    buf = f.read(CHUNK_SIZE)
                    if not buf:
                        break
                    file_size += len(buf)
                    hasher.update(buf)
            fingerprint = hasher.hexdigest()

            # Validate NPZ shape and classes
            try:
                sample_count, class_count = _validate_npz_dataset(
                    temp_path,
                    expected_num_classes=dataset.num_classes,
                )
            except ValueError as exc:
                raise HTTPException(
                    status_code=status.HTTP_422_UNPROCESSABLE_ENTITY,
                    detail=f"Dataset validation failed: {exc}",
                ) from exc

            # Commit to final storage location
            temp_path.replace(final_path)

            version = DatasetVersion(
                dataset_id=dataset.id,
                version=version_name,
                sample_count=sample_count,
                fingerprint=fingerprint,
            )

            db.add(version)
            dataset.sample_count = sample_count

            db.commit()
            db.refresh(version)

            record_audit(
                db,
                actor_user_id=actor_user_id,
                action="DATASET_VERSION_LINKED",
                resource_type="dataset",
                resource_id=dataset.id,
                result="SUCCESS",
                metadata={
                    "version_id": version.id,
                    "version": version.version,
                    "record_link": record_link,
                    "file_size": file_size,
                    "fingerprint": fingerprint,
                    "sample_count": sample_count,
                    "class_count": class_count,
                    "storage": "hospital_local",
                    "validation": "NPZ_SAFE_NO_PICKLE",
                },
            )

            return version, file_size, fingerprint, class_count

        except HTTPException:
            temp_path.unlink(missing_ok=True)
            raise
        except Exception as exc:
            temp_path.unlink(missing_ok=True)
            final_path.unlink(missing_ok=True)
            db.rollback()
            raise HTTPException(
                status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
                detail=f"Dataset record ingestion failed: {exc}",
            ) from exc

    # ========================================================================
    # LIST VERSIONS
    # ========================================================================

    @staticmethod
    def list_versions(
        db: Session,
        *,
        hospital_id: str,
        dataset_id: str,
    ) -> list[DatasetVersion]:

        dataset = DatasetService.get_dataset(
            db,
            hospital_id=hospital_id,
            dataset_id=dataset_id,
        )

        return (
            db.query(DatasetVersion)
            .filter(
                DatasetVersion.dataset_id == dataset.id
            )
            .order_by(DatasetVersion.created_at.desc())
            .all()
        )

    # ========================================================================
    # ACTIVE STATE
    # ========================================================================

    @staticmethod
    def set_active(
        db: Session,
        *,
        hospital_id: str,
        actor_user_id: str,
        dataset_id: str,
        active: bool,
    ) -> Dataset:

        dataset = DatasetService.get_dataset(
            db,
            hospital_id=hospital_id,
            dataset_id=dataset_id,
        )

        dataset.is_active = active

        db.commit()
        db.refresh(dataset)

        record_audit(
            db,
            actor_user_id=actor_user_id,
            action=(
                "DATASET_ACTIVATED"
                if active
                else "DATASET_DEACTIVATED"
            ),
            resource_type="dataset",
            resource_id=dataset.id,
            result="SUCCESS",
        )

        return dataset
