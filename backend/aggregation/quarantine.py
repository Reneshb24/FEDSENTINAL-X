"""
FedSentinel quarantine policy.

Quarantine separates potentially unsafe updates from the aggregation
path while preserving them as evidence for later security analysis.

Important:
    Quarantine is an enforcement mechanism, not a maliciousness verdict.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Iterable

from backend.core.types import Action
from backend.models.update import ModelUpdate


@dataclass(frozen=True)
class QuarantineDecision:
    """Decision for one model update."""

    update_id: str
    client_id: str

    quarantined: bool

    action: Action

    reason: str


@dataclass(frozen=True)
class QuarantineResult:
    """Result of applying quarantine to a collection of updates."""

    accepted_updates: list[ModelUpdate]
    quarantined_updates: list[ModelUpdate]

    decisions: list[QuarantineDecision]

    @property
    def accepted_count(self) -> int:
        """Number of updates allowed toward aggregation."""

        return len(self.accepted_updates)

    @property
    def quarantined_count(self) -> int:
        """Number of updates isolated from aggregation."""

        return len(self.quarantined_updates)


class QuarantineManager:
    """
    Apply an explicit security policy to model updates.

    The manager does not determine whether an update is malicious.
    It receives evidence from previous detection layers and applies
    the configured enforcement policy.
    """

    def __init__(
        self,
        *,
        quarantine_outliers: bool = True,
    ) -> None:

        self.quarantine_outliers = (
            quarantine_outliers
        )

    def apply(
        self,
        updates: Iterable[ModelUpdate],
        outlier_client_ids: set[str] | None = None,
    ) -> QuarantineResult:
        """
        Separate detected outliers from accepted updates.

        Args:
            updates:
                Model updates generated by federation clients.

            outlier_client_ids:
                Client IDs identified as L2 outliers.

        Returns:
            QuarantineResult containing accepted and isolated updates.
        """

        update_list = list(updates)

        if not update_list:
            raise ValueError(
                "At least one update is required."
            )

        if outlier_client_ids is None:
            outlier_client_ids = set()

        accepted_updates: list[ModelUpdate] = []

        quarantined_updates: list[ModelUpdate] = []

        decisions: list[QuarantineDecision] = []

        for update in update_list:

            should_quarantine = (
                self.quarantine_outliers
                and update.client_id
                in outlier_client_ids
            )

            if should_quarantine:

                quarantined_updates.append(
                    update
                )

                decisions.append(
                    QuarantineDecision(
                        update_id=update.update_id,
                        client_id=update.client_id,
                        quarantined=True,
                        action=Action.QUARANTINE,
                        reason=(
                            "Update isolated from aggregation "
                            "because Layer 2 identified it as "
                            "a statistical outlier."
                        ),
                    )
                )

            else:

                accepted_updates.append(
                    update
                )

                decisions.append(
                    QuarantineDecision(
                        update_id=update.update_id,
                        client_id=update.client_id,
                        quarantined=False,
                        action=Action.ALLOW,
                        reason=(
                            "Update remains eligible for "
                            "aggregation under the current "
                            "quarantine policy."
                        ),
                    )
                )

        return QuarantineResult(
            accepted_updates=accepted_updates,
            quarantined_updates=quarantined_updates,
            decisions=decisions,
        )